u16 modExpon(u8* privKey,u8* G_Arr,u16 keyLeng,u8* P_Arr,u8* pubKey)
{
	  u8 					nump[LENGTH_DH_2048];
		big 				mod;
		big 				exponent;
		big 				inputMessage;
		big 				outputMessage;
		u16 				keyByteLength;
		u16 				digitNum;
		miracl 				* mip;
		keyByteLength 		= keyLeng;
		digitNum  			= keyByteLength << 1;
		mip 				= mirsys(digitNum, 16);

		mod 				= mirvar(0);
		exponent 			= mirvar(0);
		inputMessage 		= mirvar(0);
		outputMessage 		= mirvar(0);

		mip->IOBASE 		= 16;
		//N

	    ecpMem_Copy(nump, P_Arr, keyByteLength);
		bytes_to_big(keyByteLength, nump, mod);
		//E

	    ecpMem_Copy(nump, privKey, keyByteLength);
		bytes_to_big(keyByteLength, nump, exponent);

	    ecpMem_Copy(nump, G_Arr, keyByteLength);
		bytes_to_big(keyByteLength, nump, inputMessage);
		powmod(inputMessage, exponent, mod, outputMessage);
		big_to_bytes(keyByteLength, outputMessage, pubKey, TRUE);

	    //Cleans up after the current instance of MIRACL, and frees all internal variables.
	    //A subsequent call to mirsys() will re-initialise the MIRACL system
	    //Must be called after mirsys()
	    mirexit();

	    return ALG_OK;
}

u16 genDHPubKey(u8* privKey,u8* pubKey,u8* G_Arr,u16 keyLeng,u8* P_Arr)
{
	u16 rtn;
	u8 tempBuf[256];
	rtn 					= ALG_ERROR;
	rtn = modExpon(privKey,G_Arr,keyLeng,P_Arr,tempBuf);
	memCopyNoAtomic(pubKey,tempBuf,keyLeng);
	return rtn;
}


