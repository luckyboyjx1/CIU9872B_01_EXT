u8 mifareLib_CmdParaInit(mifareLib_cmd_para_t *	myMifareLib_cmdPara, u8 currentBlockNumber)
{
	PM8						tempCurrentBlockAdd;
	u8						tempCurrentSector;
	u8						tempRelatiBlock;
	u8						tempCurrentBlock;
	u8						paraInitResult;
	u8						accCondIndex;
	tempCurrentBlock		= currentBlockNumber;
	paraInitResult			= 0x00;

	//block[0,127]:sector[0,31],block[128,255]:sector[32,39]
	if(tempCurrentBlock & 0x80)
	{
		tempRelatiBlock			= tempCurrentBlock & 0x0F;
		tempCurrentSector		= (tempCurrentBlock >> 4) & 0x07;
		tempCurrentBlockAdd		= MEMtPM8(U8_M_U16(tempCurrentSector, 0x100) + 0x800);
		tempCurrentSector		+= 0x20;
		accCondIndex			= MIFARE_AUTH_KEY_M4_OFFSET;
	}
	else
	{
		tempRelatiBlock			= tempCurrentBlock & 0x03;
		tempCurrentSector		= tempCurrentBlock >> 2;
		tempCurrentBlockAdd		= MEMtPM8(U8_M_U16(tempCurrentSector, 0x40));
		accCondIndex			= MIFARE_AUTH_KEY_M1_OFFSET;
	}

	tempCurrentBlockAdd			= PM8_A_U32(MifareLib_getMifareAddress(), tempCurrentBlockAdd);

	myMifareLib_cmdPara->currentBlockAdd 	= PM8_A_U16(tempCurrentBlockAdd, U8_M_U8(tempRelatiBlock, MIFARE_BLOCK_SIZE));
	myMifareLib_cmdPara->currentSector 		= tempCurrentSector;
	myMifareLib_cmdPara->relatiBlock 		= tempRelatiBlock;
	myMifareLib_cmdPara->accCondBlockAdd	= PM8_A_U32(tempCurrentBlockAdd, accCondIndex);

	return paraInitResult;
}

