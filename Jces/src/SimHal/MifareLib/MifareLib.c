//uint8 sector:扇区序号
//uint8 block:块序号
//uint8 key:可操作的密钥类型.0-keya,1-keyb,2-keyab,3-never
//uint8 config:访问命令
//bit0~1:MIFARE_R-read,MIFARE_W-write,MIFARE_I-inc,MIFARE_DRT-dec/restore/transfer
//uint8:访问权限
//bit0:数据块/制造块.0-无,1-有.
//bit1:控制块keya区.0-无,1-有.
//bit2:控制块ctrl区.0-无,1-有.
//bit3:控制块keyb区.0-无,1-有.
u8 MifareLib_checkAcce(PM8 accCondBlockAdd, u8 currentSector, u8 relatiBlock, u8 key, u8 config)
{
	PM8					currentAccePoint;
	u8					accessCondition[4];
	u8					accCondChecRes;
	u8 					temp;
	u8 					control;

	currentAccePoint			= PM8_A_U8(accCondBlockAdd, MIFARE_ACCESS_COND_OFFSET);
	ecpMem_Copy(accessCondition, currentAccePoint, 0x04);
	if(
			(((accessCondition[0] & 0x0f) 	^ (accessCondition[1] >> 0x04))	!= 0x0f) ||
			(((accessCondition[1] & 0x0f) 	^ (accessCondition[2] >> 0x04))	!= 0x0f) ||
			(((accessCondition[2] & 0x0f)	^ (accessCondition[0] >> 0x04))	!= 0x0f)
		)
	{
		return 0x0;
	}

	//manufacture block
	if ((0x00 == currentSector) && (0x00 == relatiBlock))
	{
		if(MIFARE_R == config)
		{
			return 0x01;
		}
		else
		{
			return 0x00;
		}
	}
	//data block
	if(currentSector < 0x20)
	{
		temp					= relatiBlock;
	}
	else
	{
		temp					= relatiBlock / 5;
	}

	control						=  (accessCondition[1] & (1 << (4 + temp))) 		>> (2 + temp);
	control						+= (accessCondition[2] & (1 << (4 + temp)))			>> (4 + temp);
	control						+= ((accessCondition[2] & (1 << temp)) >> temp) 	<< 1;

	if (temp != 3)
	{
		return (MIFARE_KEY_TYPE_AB == MifareLb_data[control][config]) || (MifareLb_data[control][config] == key ? 0x1 : 0x0);
	}
	//control block
	if ((config != MIFARE_R) && (config != MIFARE_W))
	{
		return 0x0;
	}

	accCondChecRes			= 0x0;

	if (MIFARE_W == config)
	{
		control 	+= 8;
	}
	if (/*((MIFARE_KEY_NEVER != MifareLb_key[control][0]) && (MIFARE_KEY_TYPE_AB == key)) || */(MifareLb_key[control][0] == key) || (MIFARE_KEY_TYPE_AB == MifareLb_key[control][0]))//keya
	{
		accCondChecRes 		|= 0x2;
	}
	if (/*((MIFARE_KEY_NEVER != MifareLb_key[control][1]) && (MIFARE_KEY_TYPE_AB == key)) || */(MifareLb_key[control][1] == key) || (MIFARE_KEY_TYPE_AB == MifareLb_key[control][1]))//ctrl
	{
		accCondChecRes 		|= 0x4;
	}
	if (/*((MIFARE_KEY_NEVER != MifareLb_key[control][2]) && (MIFARE_KEY_TYPE_AB == key)) || */(MifareLb_key[control][2] == key) || (MIFARE_KEY_TYPE_AB == MifareLb_key[control][2]))//keyb
	{
		accCondChecRes 		|= 0x8;
	}

	return accCondChecRes;
}


